// One-time local setup: generates random secrets and MySQL account passwords.
//
//   npm run init:env
//
// Writes (all git-ignored):
//   backend/.env                          from .env.example, placeholders replaced
//   ai-service/.env                       shared secret for the internal API
//   database/setup/setup.local.sql        run ONCE as MySQL root: creates databases + accounts
//
// Nothing is printed to the console except file paths. Existing files are never overwritten.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..', '..');
const BACKEND_ENV = path.join(ROOT, 'backend', '.env');
const AI_ENV = path.join(ROOT, 'ai-service', '.env');
const SETUP_SQL = path.join(ROOT, 'database', 'setup', 'setup.local.sql');

const hex = (bytes) => crypto.randomBytes(bytes).toString('hex');

function fillTemplate(templatePath, values) {
  let text = fs.readFileSync(templatePath, 'utf8');
  for (const [key, value] of Object.entries(values)) {
    const line = new RegExp(`^${key}=.*$`, 'm');
    if (!line.test(text)) throw new Error(`${key} not found in ${templatePath}`);
    text = text.replace(line, `${key}=${value}`);
  }
  return text;
}

function buildSetupSql({ appPassword, migratorPassword, backupPassword }) {
  const hosts = ['localhost', '127.0.0.1'];
  const lines = [
    '-- FinTrack local database setup. Generated by backend/scripts/init-env.js.',
    '-- Run ONCE as MySQL root. Contains passwords: this file is git-ignored, do not share it.',
    '',
    'CREATE DATABASE IF NOT EXISTS fintrack      CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;',
    'CREATE DATABASE IF NOT EXISTS fintrack_test CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;',
    '',
    '-- Lets a non-SUPER account (the migrator) create the audit-log triggers while binary',
    '-- logging is on. Server-wide setting; safe for a development machine.',
    'SET PERSIST log_bin_trust_function_creators = ON;',
    '',
  ];
  for (const host of hosts) {
    lines.push(
      `-- Accounts for connections from ${host}`,
      `CREATE USER IF NOT EXISTS 'fintrack_migrator'@'${host}' IDENTIFIED BY '${migratorPassword}';`,
      `CREATE USER IF NOT EXISTS 'fintrack_app'@'${host}'      IDENTIFIED BY '${appPassword}';`,
      `CREATE USER IF NOT EXISTS 'fintrack_backup'@'${host}'   IDENTIFIED BY '${backupPassword}';`,
      `ALTER USER 'fintrack_migrator'@'${host}' IDENTIFIED BY '${migratorPassword}';`,
      `ALTER USER 'fintrack_app'@'${host}'      IDENTIFIED BY '${appPassword}';`,
      `ALTER USER 'fintrack_backup'@'${host}'   IDENTIFIED BY '${backupPassword}';`,
      '',
      '-- Migrator: owns the schema and hands table-level privileges to the app account.',
      `GRANT ALL PRIVILEGES ON fintrack.*      TO 'fintrack_migrator'@'${host}' WITH GRANT OPTION;`,
      `GRANT ALL PRIVILEGES ON fintrack_test.* TO 'fintrack_migrator'@'${host}' WITH GRANT OPTION;`,
      '',
      '-- App: no privileges here. The migration runner grants them table by table',
      '-- (audit_logs is SELECT + INSERT only).',
      '',
      '-- Backup: read-only.',
      `GRANT SELECT, LOCK TABLES, SHOW VIEW, TRIGGER ON fintrack.* TO 'fintrack_backup'@'${host}';`,
      ''
    );
  }
  lines.push("SELECT 'FinTrack databases and accounts are ready' AS status;", '');
  return lines.join('\n');
}

function main() {
  const existing = [BACKEND_ENV, AI_ENV, SETUP_SQL].filter((file) => fs.existsSync(file));
  if (existing.length) {
    console.error('Refusing to overwrite existing files:');
    existing.forEach((file) => console.error(`  ${path.relative(ROOT, file)}`));
    console.error('Delete them first if you really want new secrets (existing data encrypted with the old keys becomes unreadable).');
    process.exit(1);
  }

  const appPassword = hex(24);
  const migratorPassword = hex(24);
  const backupPassword = hex(24);
  const aiSecret = hex(32);

  fs.writeFileSync(
    BACKEND_ENV,
    fillTemplate(path.join(ROOT, 'backend', '.env.example'), {
      DB_PASSWORD: appPassword,
      DB_MIGRATOR_PASSWORD: migratorPassword,
      DB_BACKUP_PASSWORD: backupPassword,
      JWT_ACCESS_SECRET: hex(32),
      ENCRYPTION_KEYS: `1:${hex(32)}`,
      AUDIT_HMAC_KEY: hex(32),
      AI_SERVICE_SHARED_SECRET: aiSecret,
    })
  );
  fs.writeFileSync(
    AI_ENV,
    fillTemplate(path.join(ROOT, 'ai-service', '.env.example'), { AI_SERVICE_SHARED_SECRET: aiSecret })
  );
  fs.writeFileSync(SETUP_SQL, buildSetupSql({ appPassword, migratorPassword, backupPassword }));

  console.log('Created:');
  for (const file of [BACKEND_ENV, AI_ENV, SETUP_SQL]) console.log(`  ${path.relative(ROOT, file)}`);
  console.log('\nNext: run database/setup/setup.local.sql once as MySQL root (see database/README.md).');
}

main();
